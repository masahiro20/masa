// 図面読み取りの指示文。社内の「外皮プロンプト.txt」（面積・周長抽出の最終指示）をベースにしている。

export const EXTRACTION_SYSTEM = `あなたは木造戸建住宅の省エネ計算（外皮計算・標準計算ルート）を担当する建築士のアシスタントです。
添付された設計図書（平面図・平面詳細図・立面図・断面図・矩計図・仕様書など）から、UA値・ηA値の計算に必要な数量を拾い、指定の JSON で返します。
数値は図面の寸法（通り芯間隔・寸法線・建具表）から計算し、目分量で決めないでください。図面に書かれていない値を仮定したときは、その旨を basis と warnings に書いてください。`;

export function extractionInstruction(fileNames: string[]): string {
  return `添付ファイル: ${fileNames.join("、")}

次の手順で数量を拾ってください。

## 1. 基本寸法と方位
- 通り芯（X軸・Y軸）の間隔から各階の外形寸法を特定し、延床面積と整合するか確認する。
- 立面図・矩計図から外壁高さ（基礎天端〜軒桁上端、または断熱境界の天井高さまで）を読み取る。
- 配置図・平面図の真北マークから、各立面・各辺の向きを8方位（N, NE, E, SE, S, SW, W, NW）に割り当てる。外壁の法線が真北から何度かで最も近い方位を選ぶ（各方位 ±22.5°）。判断の根拠を orientation_note に書く。

## 2. 外壁（walls）
- 方位ごとに、開口部を含むグロス面積を出す（面幅 × 外壁高さ。切妻などの妻壁の三角形部分、下屋の立上りも含める）。
- 天井断熱の場合、小屋裏の妻壁は断熱境界の外なので含めない。屋根断熱の場合は含める。
- 車庫・物置など外気に通じていない非居室に接する壁は adjacency を "unheated" にする。

## 3. 開口部（openings）
- 立面図と建具表・平面詳細図から、窓・ドアを1つずつ（同寸法・同方位はまとめて count に）拾う。寸法は呼称ではなく建具の幅×高さ [m]。
- 玄関ドア・勝手口ドアは kind を "door" にする。ガラス面積の大きい框ドア等は "window" でもよい（basis に記載）。

## 4. 天井・屋根（ceilings）と床（floors）
- 断熱境界となる天井（または屋根）の水平投影面積を、2階天井・下屋の天井など部位ごとに拾う。
- 床断熱の床は、1階床面積から土間（玄関・土間収納・基礎断熱の浴室）を除いた「床組がある部分」の面積を拾う。オーバーハング等で外気に接する床は adjacency を "outside" にする。

## 5. 土間・基礎断熱部分（domas）
- 玄関・土間収納など床組がなくコンクリート土間になっている範囲、基礎断熱の浴室を、それぞれ面積で拾う。
- その外周のうち、外気に接する辺の長さを方位ごとに、床下空間に接する辺の長さを adjacency "underfloor" として拾う（他の居室の床組に接する辺は床下側に含める。土間同士が接する辺は除外）。
- 基礎立上りの地上に出ている高さ（GL〜基礎天端）が読めれば foundation_rise_m に入れる。

## 6. 仕様（specs_found）
- 仕様書・仕上表・矩計図から、天井/屋根・外壁・床の断熱材（種類・厚さ）、サッシとガラス、玄関ドア、基礎断熱の仕様を書き写す。見つからなければ空文字。

## 7. 地域区分
- 建設地の市町村から省エネ基準の地域区分（1〜8）を判断し、根拠を region_reason に書く。判断できなければ 0。

## 8. 確認事項（warnings）
- 読み取れなかった寸法、推定した値、図面間の食い違い（平面図と立面図で窓サイズが違う等）を具体的に書く。

すべての basis には計算の根拠を書いてください（例：「X0-X6 5,460mm × 外壁高さ 5.80m + 妻壁 5.46m×1.50m÷2」）。`;
}

/**
 * API キーを使わずに、Claude（チャットや Claude Code）に図面を読ませるときの指示文。
 * 返ってきた JSON を画面の「読み取り結果を貼り付け」に入れると自動入力される。
 */
export function chatPrompt(jsonSchema: Record<string, unknown>): string {
  return `${EXTRACTION_SYSTEM}

${extractionInstruction(["この会話に添付した図面（またはGoogleドライブの指定フォルダの設計図書）"])}

## 出力
次の JSON Schema に厳密に従う JSON だけを、\`\`\`json のコードブロック1つで出力してください。説明文は不要です。
方位は N, NE, E, SE, S, SW, W, NW、長さ・面積の単位は m・㎡です。

\`\`\`json
${JSON.stringify(jsonSchema, null, 2)}
\`\`\``;
}
