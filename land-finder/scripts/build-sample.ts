function parseRoadSpec(spec: string): RoadAccess[] {
  return spec.split(',').map((s) => {
    const m = s.match(/^(北東|北西|南東|南西|北|東|南|西)([\d.]+)(公|私)(2項)?$/);
    if (!m) throw new Error(`bad road spec ${s}`);
    const width = Number(m[2]);
    return {
      direction: m[1] as Direction,
      width,
      frontage: 8 + ((width * 7) % 5),
      kind: m[3] === '公' ? '公道' : '私道',
      article: m[4] ? '42条2項' : width >= 4 ? '42条1項1号' : undefined,
    };
  });
}

function parseStation(s: string) {
  const m = s.match(/^(.+?)「(.+?)」(?:徒歩(\d+)分|バス(\d+)分 停歩(\d+)分)$/);
  if (!m) throw new Error(`bad station ${s}`);
  return m[3]
    ? { line: m[1], name: m[2], walk: Number(m[3]) }
    : { line: m[1], name: m[2], bus: Number(m[4]), walk: Number(m[5]) };
}

async function main() {
  const out: Listing[] = [];
  for (const [i, [pref, city, town, price, area, station, zoning, [cov, far], roads, extra = {}]] of ROWS.entries()) {
    const g = await geocode(`${pref}${city}${town}`);
    if (!g) console.warn('geocode failed', pref, city, town);
    const { tag, ...rest } = extra;
    const road = parseRoadSpec(roads);
    const shape = rest.shape ?? '整形地';
    if (shape === '旗竿地') for (const r of road) r.frontage = 2.5;
    out.push({
      id: `sample-${String(i + 1).padStart(3, '0')}`,
      source: 'sample',
      sourceLabel: 'サンプルデータ',
      title: `${town} ${tag ?? '売地'}`,
      prefecture: pref,
      city,
      address: town,
      lat: g?.lat,
      lng: g?.lng,
      price,
      landArea: area,
      landAreaNote: '公簿',
      stations: [parseStation(station)],
      zoning: zoning === '指定なし' ? undefined : zoning,
      coverageRatio: cov,
      floorAreaRatio: far,
      cityPlanning: '市街化区域',
      fireZone: '指定なし',
      roads: road,
      landCategory: '宅地',
      shape,
      terrain: '平坦',
      buildingCondition: false,
      status: '更地',
      rights: '所有権',
      delivery: '相談',
      updatedAt: '2026-09-01',
      ...rest,
    });
  }
  fs.writeFileSync(path.join(DATA_DIR, 'sample-listings.json'), JSON.stringify(out, null, 2) + '\n');
  console.log(`wrote ${out.length} listings (${out.filter((l) => l.lat != null).length} geocoded)`);
}

main();
